var update = flag.Bool("update", false, "rewrite the golden files of the tests")

// maximalDocument returns a document of profile p that holds every element
// of the schema of p once, with all its attributes. The values have the
// lexical form of their type, and the values that the reader interprets
// (dates, currencies, tax type and schemes) are valid ones.
func maximalDocument(p invoice.Profile) []byte {
	b := []byte(xmlDeclaration + rootStart)
	var stack []string // type names of the open elements, against recursion
	var walk func(t schema.Type, parent schema.Type, path string)
	walk = func(t schema.Type, parent schema.Type, path string) {
		if slices.Contains(stack, t.TypeName()) {
			return
		}
		name := nsPrefix(t.Space()) + ":" + t.Name()
		path += "/" + t.Name()
		b = append(b, '<')
		b = append(b, name...)
		names, _ := t.Attrs()
		for _, a := range names {
			b = append(b, ' ')
			b = append(b, a...)
			b = append(b, `="`...)
			b = appendEscaped(b, sampleAttr(t, parent, a), true)
			b = append(b, '"')
		}
		b = append(b, '>')
		if t.Simple() {
			b = appendEscaped(b, sampleValue(t, parent, path, p), false)
		} else {
			stack = append(stack, t.TypeName())
			for _, c := range t.Children() {
				walk(c, t, path)
			}
			stack = stack[:len(stack)-1]
		}
		b = append(b, "</"...)
		b = append(b, name...)
		b = append(b, '>')
	}
	root := schema.Root(p)
	stack = append(stack, root.TypeName())
	for _, c := range root.Children() {
		walk(c, root, "")
	}
	return append(b, "</"+rootName+">"...)
}

func sampleAttr(t, parent schema.Type, name string) string {
	switch name {
	case "format":
		return "102"
	case "currencyID":
		return "EUR"
	case "unitCode":
		return "C62"
	case "mimeCode":
		return "application/pdf"
	case "filename":
		return "file.pdf"
	case "schemeID":
		if parent.Name() == "SpecifiedTaxRegistration" {
			return "VA"
		}
	}
	return t.Name() + "-" + name
}

func sampleValue(t, parent schema.Type, path string, p invoice.Profile) string {
	switch t.ValueKind() {
	case "decimal":
		return "1.50"
	case "integer":
		return "1"
	case "boolean":
		return "true"
	case "base64":
		return "aGVsbG8="
	case "date":
		return "2026-11-16"
	}
	switch {
	case strings.HasSuffix(path, "/GuidelineSpecifiedDocumentContextParameter/ID"):
		return p.URN()
	case t.Name() == "DateTimeString" || t.Name() == "DateString":
		return "20261116"
	case t.Name() == "Indicator":
		return "true"
	case t.Name() == "InvoiceCurrencyCode" || t.Name() == "SourceCurrencyCode":
		return "EUR"
	case t.Name() == "TaxCurrencyCode" || t.Name() == "TargetCurrencyCode":
		return "USD"
	case t.Name() == "TypeCode" && parent.TypeName() == "ram:TradeTaxType":
		return "VAT"
	}
	return t.Name() + "-1"
}

// unmodeledPaths reads a document and returns the locations of its
// extensions, as absolute paths of local names without positions.
func unmodeledPaths(t *testing.T, data []byte) []string {
	t.Helper()
	root, err := xmltree.Parse(data)
	if err != nil {
		t.Fatal(err)
	}
	var paths []string
	r := reader{inv: new(invoice.Invoice), unreadPaths: &paths}
	r.document(root)
	if len(r.issues) > 0 {
		t.Fatalf("issues: %v", r.issues)
	}
	positions := regexp.MustCompile(`\[[0-9]+\]|[a-z]+:`)
	for i, p := range paths {
		paths[i] = positions.ReplaceAllString(p, "")
	}
	return paths
}

// TestExtendedDataSet reads a document holding every element of the
// EXTENDED schema. The elements and attributes that the model does not carry
// are listed in testdata/extended-unmodeled.txt (go test -update rewrites
// it): they are kept as extensions, and Marshal puts the whole document back.
func TestExtendedDataSet(t *testing.T) {
	doc := maximalDocument(invoice.ProfileExtended)
	checkXSD(t, invoice.ProfileExtended, doc)

	got := unmodeledPaths(t, doc)
	golden := filepath.Join("testdata", "extended-unmodeled.txt")
	const header = "# Elements and attributes of the Factur-X 1.09.2 EXTENDED schema that\n" +
		"# invoice.Invoice has no field for. cii.Parse keeps them as extensions\n" +
		"# (invoice.Extension) and cii.Marshal writes them back. Generated by\n" +
		"# TestExtendedDataSet (go test ./cii -run TestExtendedDataSet -update).\n"
	text := header + strings.Join(got, "\n") + "\n"
	if *update {
		if err := os.WriteFile(golden, []byte(text), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	want, err := os.ReadFile(golden)
	if err != nil {
		t.Fatal(err)
	}
	if string(want) != text {
		t.Errorf("the elements outside the model changed; run go test ./cii -run TestExtendedDataSet -update and review %s", golden)
	}

	inv := mustParse(t, doc)
	if n := len(inv.Unmodeled()); n != len(got) {
		t.Errorf("Unmodeled lists %d extensions, the reader kept %d", n, len(got))
	}
	// The schema allows what the Factur-X rules forbid: a reference type
	// on a supporting document (BG-24) is the only element dropped, and it
	// is reported.
	_, err = Marshal(inv, &MarshalOptions{Strict: true})
	var le *LossError
	if !errors.As(err, &le) || !slices.Equal(le.Terms, []string{"AdditionalDocument.ReferenceTypeCode (TypeCode 130 only)"}) {
		t.Errorf("strict Marshal: %v", err)
	}
	for _, indent := range []bool{false, true} {
		out := mustMarshal(t, inv, &MarshalOptions{Indent: indent})
		checkXSD(t, invoice.ProfileExtended, out)
		orig, _ := xmltree.Parse(doc)
		back, _ := xmltree.Parse(out)
		d := diffTrees(orig, back, treeNorm{cur: inv.Currency, taxCur: inv.TaxCurrency, spec: true})
		want := []string{"CrossIndustryInvoice/SupplyChainTradeTransaction[1]/ApplicableHeaderTradeAgreement[1]/AdditionalReferencedDocument[1]/ReferenceTypeCode[1]=ReferenceTypeCode-1"}
		if !slices.Equal(d.missing, want) || len(d.added) > 0 || d.order != "" {
			t.Errorf("indent=%v: the output does not hold the tree of the original:\n%v", indent, d)
		}
		if again := mustMarshal(t, mustParse(t, out), &MarshalOptions{Indent: indent}); string(again) != string(out) {
			t.Errorf("indent=%v: second write differs from the first", indent)
		}
	}
}
