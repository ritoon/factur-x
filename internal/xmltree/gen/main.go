// Command gen writes names_gen.go: the characters above U+007F allowed in
// XML names by package xmltree.
//
// The tables are those of encoding/xml (XML 1.0, Appendix B: Letter, '_' or
// ':' first, NameChar after), derived by asking encoding/xml about every
// character of the Basic Multilingual Plane, so that xmltree accepts exactly
// the names encoding/xml accepts. Characters above U+FFFF are never allowed.
//
// Usage (from internal/xmltree, through go generate):
//
//	go run ./gen [-o names_gen.go]
package main

import (
	"bytes"
	"encoding/xml"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"strings"
)

type runeRange struct{ lo, hi rune }

func main() {
	out := flag.String("o", "names_gen.go", "output file")
	flag.Parse()

	var start, char []runeRange
	for r := rune(0x80); r <= 0xFFFF; r++ {
		if r >= 0xD800 && r <= 0xDFFF {
			continue // surrogates: not encodable in UTF-8
		}
		s := string(r)
		if accepts("<" + s + "/>") {
			start = add(start, r)
		}
		if accepts("<a" + s + "/>") {
			char = add(char, r)
		}
	}
	for r := rune(0x10000); r <= 0x10FFFF; r++ {
		if s := string(r); accepts("<"+s+"/>") || accepts("<a"+s+"/>") {
			log.Fatalf("encoding/xml accepts %U in names: extend the tables beyond the BMP", r)
		}
	}

	var b bytes.Buffer
	b.WriteString("// Code generated by go run ./gen; DO NOT EDIT.\n\npackage xmltree\n\n")
	emit(&b, "nameStartRanges", "may start an XML name", start)
	emit(&b, "nameCharRanges", "may follow the first character of an XML name", char)
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		log.Fatal(err)
	}
}

// accepts reports whether encoding/xml reads doc as a start element.
func accepts(doc string) bool {
	_, err := xml.NewDecoder(strings.NewReader(doc)).RawToken()
	return err == nil
}

func add(rs []runeRange, r rune) []runeRange {
	if n := len(rs); n > 0 && rs[n-1].hi == r-1 {
		rs[n-1].hi = r
		return rs
	}
	return append(rs, runeRange{r, r})
}

func emit(b *bytes.Buffer, name, doc string, rs []runeRange) {
	fmt.Fprintf(b, "// %s lists, in increasing order, the characters above U+007F that\n// %s.\n", name, doc)
	fmt.Fprintf(b, "var %s = [...]runeRange{\n", name)
	for i, r := range rs {
		fmt.Fprintf(b, "{0x%04X, 0x%04X},", r.lo, r.hi)
		if i%4 == 3 {
			b.WriteByte('\n')
		}
	}
	b.WriteString("\n}\n\n")
}
