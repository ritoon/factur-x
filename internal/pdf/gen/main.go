// Command gen writes ints_gen.go: the boxed values of the integers 0 to
// smallIntLimit-1, so that package pdf reads them without allocating.
//
// Converting an Int to an Object (an interface) allocates for values above
// 255; a package-level array of constant conversions is laid out by the
// linker instead, with no code run at start-up. Arrays of glyph widths, the
// largest arrays of a PDF read by package facturx, are made of such values.
//
// Usage (from internal/pdf, through go generate):
//
//	go run ./gen [-o ints_gen.go] [-n 2048]
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
)

func main() {
	out := flag.String("o", "ints_gen.go", "output file")
	n := flag.Int("n", 2048, "number of values")
	flag.Parse()

	var b bytes.Buffer
	b.WriteString("// Code generated by go run ./gen; DO NOT EDIT.\n\npackage pdf\n\n")
	fmt.Fprintf(&b, "// smallIntLimit bounds the integers held by smallInts.\nconst smallIntLimit = %d\n\n", *n)
	b.WriteString("// smallInts holds Int(i) at index i, boxed once and for all (see intObject).\n")
	b.WriteString("var smallInts = [smallIntLimit]Object{\n")
	for i := 0; i < *n; i++ {
		if i%16 == 0 {
			b.WriteString("\t")
		}
		fmt.Fprintf(&b, "Int(%d),", i)
		if i%16 == 15 || i == *n-1 {
			b.WriteString("\n")
		} else {
			b.WriteString(" ")
		}
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		log.Fatal(err)
	}
}
